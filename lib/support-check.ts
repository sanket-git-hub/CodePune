import { z } from "zod";

const supportResultSchema = z.object({
  result: z.enum(["supports", "partial", "not_supported"]),
  reason: z.string().max(200),
});

export type SupportCheckResult = z.infer<typeof supportResultSchema>;

/**
 * Checks whether an excerpt directly supports a claim statement.
 * Rule: For a claim with integrity_ok=true, sends ONLY its statement and its excerpt (already masked)
 * to Gemini (GEMINI_MODEL and GEMINI_API_KEY from env, server-side only).
 * On API failure, throws error and stores nothing.
 */
export async function checkClaimSupport(
  statement: string,
  excerpt: string
): Promise<SupportCheckResult> {
  const apiKey = process.env.GEMINI_API_KEY;
  const model = process.env.GEMINI_MODEL || "gemini-2.0-flash";

  if (!apiKey) {
    throw new Error("GEMINI_API_KEY is not configured on the server");
  }

  const prompt = `You are an evidence verification engine.
Question: Does the excerpt directly support the statement, or does it only share similar words?

Statement: "${statement}"
Excerpt: "${excerpt}"

Respond with JSON adhering to this exact schema:
{
  "result": "supports" | "partial" | "not_supported",
  "reason": "short explanation (maximum 25 words)"
}`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey}`;

  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      contents: [{ parts: [{ text: prompt }] }],
      generationConfig: {
        responseMimeType: "application/json",
      },
    }),
  });

  if (!response.ok) {
    const errorBody = await response.text().catch(() => "");
    throw new Error(`Gemini API error (${response.status}): ${errorBody || response.statusText}`);
  }

  const data = await response.json();
  const rawText = data?.candidates?.[0]?.content?.parts?.[0]?.text;

  if (!rawText) {
    throw new Error("No response generated by Gemini");
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(rawText);
  } catch {
    throw new Error("Invalid JSON returned by Gemini");
  }

  const validated = supportResultSchema.safeParse(parsed);
  if (!validated.success) {
    throw new Error("Gemini response failed schema validation: " + validated.error.message);
  }

  return validated.data;
}
